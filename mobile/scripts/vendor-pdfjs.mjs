// Regenerates src/vendor/pdfjs.generated.ts from the pdfjs-dist devDependency (legacy UMD build).
// Run: node scripts/vendor-pdfjs.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'node_modules', 'pdfjs-dist');
const pkg = JSON.parse(fs.readFileSync(path.join(dist, 'package.json'), 'utf8'));
const pick = (...c) => c.map((p) => path.join(dist, p)).find((p) => fs.existsSync(p));
const lib = pick('legacy/build/pdf.min.js', 'build/pdf.min.js');
const worker = pick('legacy/build/pdf.worker.min.js', 'build/pdf.worker.min.js');
if (!lib || !worker) throw new Error('pdfjs-dist UMD build not found (need pdfjs-dist@3.x)');
const out = path.join(root, 'src', 'vendor', 'pdfjs.generated.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out,
  `/* eslint-disable */\n// GENERATED by scripts/vendor-pdfjs.mjs from pdfjs-dist@${pkg.version} (Apache-2.0). Do not edit.\n` +
  `export const PDFJS_VERSION = ${JSON.stringify(pkg.version)};\n` +
  `export const PDFJS_SRC: string = ${JSON.stringify(fs.readFileSync(lib, 'utf8'))};\n` +
  `export const PDFJS_WORKER_SRC: string = ${JSON.stringify(fs.readFileSync(worker, 'utf8'))};\n`);
console.log(`wrote ${out} (${(fs.statSync(out).size / 1024).toFixed(0)} KB) from pdfjs-dist ${pkg.version}`);
